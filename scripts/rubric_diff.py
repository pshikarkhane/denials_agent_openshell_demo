#!/usr/bin/env python3
"""Write docs/RUBRIC_CHANGES.md: every rubric criterion whose reference/sources changed between git HEAD and the working tree. Host-only."""
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
rows, by_reason, n_cases = [], {}, 0
for p in sorted((ROOT / "data" / "cases").glob("C-*/rubric.json")):
    cid = p.parent.name
    old = subprocess.run(["git", "-C", str(ROOT), "show", f"HEAD:data/cases/{cid}/rubric.json"], capture_output=True, text=True)
    if old.returncode:
        continue
    o = {c["id"]: c for c in json.loads(old.stdout)["criteria"]}
    n = {c["id"]: c for c in json.loads(p.read_text())["criteria"]}
    assert set(o) == set(n), (cid, set(o) ^ set(n))
    ch = False
    for i, c in n.items():
        if c["reference"] != o[i]["reference"] or c["sources"] != o[i]["sources"] or c["text"] != o[i]["text"]:
            reason = ("denial reason: the EOB carries the CARC/RARC and the denial letter the reason text; either may be cited" if c["family"] == "denial_reason"
                      else "the fact appears in both the EOB and the denial letter; either may be cited")
            rows.append((cid, i, c["family"], o[i]["text"], o[i]["reference"], c["reference"], o[i]["sources"], c["sources"], reason))
            by_reason[reason] = by_reason.get(reason, 0) + 1
            ch = True
    n_cases += ch
L = ["# RUBRIC_CHANGES: relaxed references (host-only)", "",
     "Generated by `scripts/rubric_diff.py` from the change in `eval/gen_rubrics.py` (rubric.json files under `data/cases/` were regenerated; truth, documents and policy are unchanged). "
     "Rule: where the same fact legitimately appears in both the EOB and the denial letter (identifiers, amounts, dates, codes, the missing item, the denial reason), the criterion's reference now lists "
     "both files as accepted sources (\"any one is enough\") and the judge prompt (`eval/prompts/grader.md`, rule 4) says so. **Not relaxed:** criteria about clinical evidence in notes, claim_history facts, "
     "policy sections, deadlines, enclosures, traps. No criterion was added, removed or reworded (ids and texts are unchanged); auto criteria are unchanged.", "",
     f"**{len(rows)} criteria changed in {n_cases} of 60 rubrics.** By reason: " + "; ".join(f"{v} x {k}" for k, v in by_reason.items()) + ".", "",
     "| case | criterion | family | text | old reference | new reference | old sources | new sources | reason |", "|---|---|---|---|---|---|---|---|---|"]
for r in rows:
    L.append("| " + " | ".join(str(x).replace("|", "/") if not isinstance(x, list) else ", ".join(x) for x in r) + " |")
(ROOT / "docs" / "RUBRIC_CHANGES.md").write_text("\n".join(L) + "\n")
print(f"{len(rows)} changed criteria in {n_cases} rubrics")
